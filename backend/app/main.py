@app.post("/signup")
def signup(user_data: schemas.UserCreate, db: Session = Depends(get_db)):

    if len(user_data.username) < 3:
        raise HTTPException(status_code=400, detail="Username is too short. It must be at least 3 characters.")
    
    if len(user_data.username) > 20:
        raise HTTPException(status_code=400, detail="Username is too long. Maximum 20 characters allowed.")
    
    
    existing_user = db.query(models.User).filter(models.User.username == user_data.username).first()
    if existing_user:
        raise HTTPException(status_code=400, detail="Username already exists")
    
    if len(user_data.password) < 8:
        raise HTTPException(status_code=400, detail="Password is too weak. Please use at least 8 characters.")
    
    if len(user_data.password) > 12:
        raise HTTPException(status_code=400, detail="Password is too long. Please keep it between 8 and 12 characters.")
    
    # 1. Scramble the password
    hashed_pwd = get_password_hash(user_data.password)
    
    # 2. Create the User object for the database
    new_user = models.User(
        username=user_data.username, 
        password_hash=hashed_pwd
    )
    
    # 3. Save to PostgreSQL
    db.add(new_user)
    db.commit()
    db.refresh(new_user)
    
    return {"message": f"{new_user.username} created successfully!"}
    
@app.post("/login")
def login(user_data: schemas.UserLogin, db: Session = Depends(get_db)):
    # 1. Look for the doctor in the database
    user = db.query(models.User).filter(models.User.username == user_data.username).first()
    
    # 2. If the doctor doesn't exist OR the password doesn't match the scrambled hash
    if not user or not verify_password(user_data.password, user.password_hash):
        raise HTTPException(status_code=401, detail="Invalid username or password")
    
    # 3. If everything is correct, give them the "VIP Pass" (Token)
    access_token = create_access_token(data={"sub": user.username})
    
    return {
        "access_token": access_token, 
        "token_type": "bearer",
        "message": f"Welcome back, {user.username}!"
    }

@app.post("/patients", response_model=schemas.PatientResponse)
def add_patient(
    patient_in: schemas.PatientCreate, 
    db: Session = Depends(get_db), 
    current_user: models.User = Depends(get_current_user)
):
    # 1. Create the new Patient object using data from the frontend
    # and the ID of the doctor who is currently logged in
    new_patient = models.Patient(
        full_name=patient_in.full_name,
        age=patient_in.age,
        gender=patient_in.gender,
        doctor_id=current_user.id  # This links the patient to the doctor [cite: 32]
    )
    
    # 2. Add and commit to the database
    db.add(new_patient)
    db.commit()
    
    # 3. Refresh to get the new ID generated by PostgreSQL
    db.refresh(new_patient)
    
    return new_patient

@app.get("/patients", response_model=list[schemas.PatientResponse])
def get_patients(
    db: Session = Depends(get_db), 
    current_user: models.User = Depends(get_current_user)
):
    # This logic finds only the patients that belong to the logged-in doctor
    patients = db.query(models.Patient).filter(models.Patient.doctor_id == current_user.id).all()
    
    return patients

@app.get("/patients/{patient_id}", response_model=schemas.PatientResponse)
def get_one_patient(
    patient_id: int, 
    db: Session = Depends(get_db), 
    current_user: models.User = Depends(get_current_user)
):
    # Search for the specific patient by ID AND ensure they belong to this doctor
    patient = db.query(models.Patient).filter(
        models.Patient.id == patient_id, 
        models.Patient.doctor_id == current_user.id
    ).first()

    # If the patient doesn't exist (or doesn't belong to this doctor), send a 404
    if not patient:
        raise HTTPException(status_code=404, detail="Patient not found")
        
    return patient